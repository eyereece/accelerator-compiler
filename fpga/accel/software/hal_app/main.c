/* Run compiler-generated instructions.
 * All offsets below are BYTES.
 */
#include <stdint.h>
#include <stdio.h>
#include "system.h"
#include "io.h"
#include "program.h"

#define REG_START          0x000u
#define REG_STATUS         0x004u
#define REG_PROGRAM_WORDS  0x008u
#define REG_R0             0x020u
#define PROGRAM_RAM        0x800u

#define STATUS_BUSY        0x1u
#define STATUS_DONE        0x2u
#define STATUS_ERROR       0x4u

#define MAX_POLLS          1000000u
#define EXPECTED_RESULT    20u /* Reference executor result for this program. */

#if CONTROLLER_0_SPAN != 4096
#error "Controller address span must match the 4096-byte RTL interface."
#endif

int main(void)
{
    const uint32_t words = accel_program_word_count;
    const uint32_t output_reg = accel_program_output_reg;
    uint32_t output_offset;
    uint32_t status, result, i;

    printf("Compiler-generated test\n");

    if (words == 0u || words > 512u) {
        printf("FAIL: invalid program word count.\n");
        return 1;
    }

    if (words !=
        (uint32_t)(sizeof(accel_program_words) /
                   sizeof(accel_program_words[0]))) {
        printf("FAIL: word count does not match generated array.\n");
        return 1;
    }

    if (output_reg >= 8u) {
        printf("FAIL: invalid output-register index.\n");
        return 1;
    }

    output_offset = REG_R0 + 4u * output_reg;

    status = IORD_32DIRECT(CONTROLLER_0_BASE, REG_STATUS);
    if (status & STATUS_BUSY) {
        printf("FAIL: controller already busy; reset before retrying.\n");
        return 1;
    }

    /* Load the words generated by the compiler. */
    for (i = 0; i < words; ++i) {
        IOWR_32DIRECT(
            CONTROLLER_0_BASE,
            PROGRAM_RAM + 4u * i,
            accel_program_words[i]
        );
    }

    IOWR_32DIRECT(CONTROLLER_0_BASE, REG_PROGRAM_WORDS, words);

    if (IORD_32DIRECT(CONTROLLER_0_BASE, REG_PROGRAM_WORDS) != words) {
        printf("FAIL: program-length readback mismatch.\n");
        return 1;
    }

    printf("Loaded %lu program words.\n", (unsigned long)words);
    printf("Output register: R%lu\n", (unsigned long)output_reg);

    /* START clears previous flags and accelerator registers. */
    IOWR_32DIRECT(CONTROLLER_0_BASE, REG_START, 1u);

    /* Completion may occur before the first status read. */
    for (i = 0; i < MAX_POLLS; ++i) {
        status = IORD_32DIRECT(CONTROLLER_0_BASE, REG_STATUS);

        if (status & STATUS_ERROR) {
            printf(
                "FAIL: controller ERROR, status=0x%08lx\n",
                (unsigned long)status
            );
            return 1;
        }

        if (!(status & STATUS_BUSY) && (status & STATUS_DONE)) {
            break;
        }
    }

    if (i == MAX_POLLS) {
        printf(
            "FAIL: polling limit reached, status=0x%08lx\n",
            (unsigned long)status
        );
        return 1;
    }

    /* Read the output register selected by the compiler. */
    result = IORD_32DIRECT(CONTROLLER_0_BASE, output_offset);

    printf("STATUS=0x%08lx\n", (unsigned long)status);
    printf(
        "R%lu=%lu\n",
        (unsigned long)output_reg,
        (unsigned long)result
    );

    if (result != EXPECTED_RESULT) {
        printf(
            "FAIL: expected %lu from reference execution.\n",
            (unsigned long)EXPECTED_RESULT
        );
        return 1;
    }

    printf("PASS: FPGA result matches reference result.\n");
    return 0;
}