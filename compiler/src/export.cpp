#include "export.h"

#include <fstream>
#include <iomanip>
#include <ostream>
#include <stdexcept>

namespace accel {
namespace {

// Print exactly 8 hex digits, then restore decimal formatting
void hex_word(std::ostream& out, std::uint32_t word) {
    out << "0x" << std::hex << std::uppercase
        << std::setw(8) << std::setfill('0') << word
        << std::dec << std::setfill(' ');
}

// Check for errors, including those encountered when closing the file
void finish(std::ofstream& out, const std::string& path) {
    out.close();

    if (!out) {
        throw std::runtime_error("Failed to write " + path);
    }
}
}   // namespace

void export_program(const std::vector<std::uint32_t>& words,
                    std::uint32_t output_reg,
                    const std::string& prefix) {
    if (words.empty() || words.size() > 512 || output_reg >= 8) {
        throw std::runtime_error("Invalid program size or output register for export");
    }
    const std::string listing_path = prefix + ".txt";
    const std::string header_path = prefix + ".h";
    const std::string binary_path = prefix + ".bin";

    // ----- READABLE LISTING -----
    std::ofstream listing(listing_path);

    if (!listing) {
        throw std::runtime_error("Cannot open " + listing_path);
    }

    listing << "Program words: " << words.size()
            << "\nOutput register: R" << output_reg << "\n\n";

    bool immediate = false;

    for (std::size_t pc = 0; pc < words.size(); ++pc) {
        const std::uint32_t word = words[pc];

        listing << pc << ": ";
        hex_word(listing, word);
        listing << "  ";

        if (immediate) {
            // A LOAD_IMM data word must not be decoded as an instruction
            listing << "DATA " << word;
            immediate = false;
        } else {
            const std::uint32_t opcode = word >> 28;
            const std::uint32_t rd = (word >> 25) & 7u;
            const std::uint32_t ra = (word >> 22) & 7u;
            const std::uint32_t rb = (word >> 19) & 7u;

            if (opcode == 0) {
                listing << "HALT";
            } else if (opcode == 1) {
                listing << "LOAD_IMM R" << rd;
                immediate = true;
            } else if (opcode >= 2 && opcode <= 4) {
                const char* name = 
                    opcode == 2 ? "ADD" :
                    opcode == 3 ? "SUB" : "MUL";

                listing << name << " R" << rd
                        << ", R" << ra << ", R" << rb;
            } else {
                listing << "INVALID OPCODE" << opcode;
            }
        }
        listing << '\n';

    }

    finish(listing, listing_path);

    // ----- C HEADER FOR NIOS APP -----
    std::ofstream header(header_path);

    if (!header) {
        throw std::runtime_error("Cannot open " + header_path);
    }

    header << "/* Generated by the accel compiler. */\n"
            << "#ifndef ACCEL_GENERATED_PROGRAM_H\n"
            << "#define ACCEL_GENERATED_PROGRAM_H\n\n"
            << "#include <stdint.h>\n\n"
            << "static const uint32_t accel_program_words[] = {\n";

    for (const std::uint32_t word : words) {
        header << "    ";
        hex_word(header, word);
        header << "u,\n";
    }

    header << "};\n\n"
            << "static const uint32_t accel_program_word_count = "
            << words.size() << "u;\n"
            << "static const uint32_t accel_program_output_reg = "
            << output_reg << "u;\n\n"
            << "#endif\n";

    finish(header, header_path);

    // ----- BIN FILE: LSB FIRST -----

    std::ofstream binary(binary_path, std::ios::binary);

    if (!binary) {
        throw std::runtime_error("Cannot open " + binary_path);
    }

    for (const std::uint32_t word : words) {    // e.g., 0x12345678
        const unsigned char bytes[4] = {
            static_cast<unsigned char>(word & 0xffu),           // byte 0: bits 0 - 7: 0x78
            static_cast<unsigned char>((word >> 8) & 0xffu),    // byte 1: bits 8 - 15: 0x56
            static_cast<unsigned char>((word >> 16) & 0xffu),   // byte 2: bits 16 - 23: 0x34
            static_cast<unsigned char>((word >> 24) & 0xffu)    // byte 3: bits 24 - 31: 0x12
        };

        binary.write(
            reinterpret_cast<const char*>(bytes),
            sizeof(bytes)
        );
    }

    finish(binary, binary_path);

}
}   // namespace accel